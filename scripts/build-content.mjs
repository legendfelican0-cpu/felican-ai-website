/* ------------------------------------------------------------ prose helpers */

// Renders a content section object into prose HTML. `p` and `p2` are paragraph
// arrays, `ul`/`ol` are lists, `note` is a callout, `links` becomes a link list.
function section(s) {
  const out = [];
  if (s.h) out.push(`<h2>${esc(s.h)}</h2>`);
  for (const paragraph of s.p || []) out.push(`<p>${paragraph}</p>`);
  if (s.ul) out.push(`<ul>${s.ul.map(li => `<li>${li}</li>`).join('')}</ul>`);
  if (s.ol) out.push(`<ol>${s.ol.map(li => `<li>${li}</li>`).join('')}</ol>`);
  for (const paragraph of s.p2 || []) out.push(`<p>${paragraph}</p>`);
  if (s.note) out.push(`<p class="note"><strong>Worth saying:</strong> ${s.note}</p>`);
  if (s.links) {
    out.push(`<ul>${s.links.map(l => `<li><a href="${l.href}">${esc(l.label)}</a>${l.note ? ` — ${esc(l.note)}` : ''}</li>`).join('')}</ul>`);
  }
  return out.join('\n');
}

const sectionsToProse = list => prose(list.map(section));

