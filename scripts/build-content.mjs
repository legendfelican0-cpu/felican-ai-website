/* ------------------------------------------------------------------ sitemap */

function buildSitemap() {
  // Generated rather than hand-maintained: the previous static file already omitted
  // /starter-pack/, and hand-editing 70 entries guarantees drift. changefreq and
  // priority are deliberately omitted — Google ignores both.
  const existing = [
    '/', '/products/', '/services/', '/education/', '/books/', '/about/',
    '/contact/', '/booking/', '/starter-pack/', '/starter-pack/ai-engines/',
    '/privacy/', '/terms/',
  ];
  const today = new Date().toISOString().slice(0, 10);
  const urls = [...new Set([...existing, ...written])].sort();
  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${ORIGIN}${u}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`;
  writeFileSync(join(OUT, 'sitemap.xml'), xml);
  return urls.length;
}

