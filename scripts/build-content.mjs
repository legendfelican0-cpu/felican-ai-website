const BANNER = '<!-- Generated by scripts/build-content.mjs — do not edit by hand. Edit content/*.js instead. -->\n';

const written = [];
const needsReview = [];

function write(urlPath, html) {
  const file = join(OUT, urlPath.replace(/^\//, ''), 'index.html');
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, BANNER + html);
  written.push(urlPath);
}

