function productGraph(product) {
  const url = `${ORIGIN}/products/${product.slug}/`;
  // SoftwareApplication, never Product. Google's Product rich result requires one of
  // offers / review / aggregateRating, and these pages deliberately show no price —
  // prices live in server/checkout.js and appear only on /starter-pack/. A Product
  // node here would be invalid by construction; Search Console flagged exactly this
  // on the pre-existing /products/ markup (19 invalid items, "Either offers, review,
  // or aggregateRating should be specified"). SoftwareApplication is accurate for
  // every one of these and carries no offers requirement.
  return [
    {
      '@type': 'SoftwareApplication',
      '@id': `${url}#product`,
      name: product.name,
      url,
      description: product.description,
      ...(product.image ? { image: abs(product.image) } : {}),
      applicationCategory: 'BusinessApplication',
      operatingSystem: 'Web',
      publisher: { '@id': `${ORIGIN}/#organization` },
    },
  ];
}

function buildProduct(product) {
  const path = `/products/${product.slug}/`;
  const trail = [HOME, { label: 'Products', href: '/products/' }, { label: product.name, href: path }];
  const body = [
    hero({
      eyebrow: product.tag,
      h1: product.name,
      lede: esc(product.lede),
      ctas: [
        { label: `Ask about ${product.name}`, href: `/contact/?product=${encodeURIComponent(product.name)}` },
        { label: 'Book a call', href: '/booking/' },
      ],
    }),
    product.facts.length ? keyFacts(product.facts) : '',
    product.image
      ? `<section class="band"><div class="shell"><figure>${picture({
          src: product.image,
          alt: `${product.name} product screenshot`,
          width: 1200,
          height: 750,
        })}<figcaption>${esc(product.name)}</figcaption></figure></div></section>`
      : '',
    sectionsToProse(product.sections),
    product.faq.length ? faq(product.faq) : '',
    product.related.length ? relatedLinks({ links: product.related }) : '',
    cta({
      heading: `Talk to us about ${product.name}`,
      body: 'A short call, and a straight answer about whether this fits your business.',
      primary: { label: 'Book a call', href: '/booking/' },
      secondary: { label: 'Send a message', href: `/contact/?product=${encodeURIComponent(product.name)}` },
    }),
  ].filter(Boolean).join('\n');

  write(path, page({
    title: product.title,
    description: product.description,
    canonical: path,
    trail,
    extraGraph: productGraph(product),
    image: product.image,
    imageAlt: `${product.name} — Felican AI`,
    body,
    activeNav: '/products/',
  }));
}

