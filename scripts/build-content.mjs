#!/usr/bin/env node
// Renders every generated content page into public/.
//
// Run with `npm run build:content`. Idempotent — safe to re-run; it overwrites the
// files it owns and touches nothing else. Every file it writes carries a generated
// banner comment naming this script, so nobody hand-edits a page that will be
// regenerated.
//
// Review rail: case studies marked `reviewNeeded: true` ARE written, but every run
// prints them as an explicit review list. Their solution descriptions were inferred
// from client needs rather than verified against what was deployed, and each also
// needs the client's permission to be named publicly. Clear the flag per entry in
// content/case-studies.js as each one is checked.

